#!/usr/bin/env python3
"""Emit the M-mode shared I-cache replay table from a trace-model result."""
import argparse
import collections
import json
from pathlib import Path


def render(result):
    table = result["fixed_shared_prefix"]
    lines = table["lines"]
    if table["line_count"] != len(lines) or not 0 < len(lines) <= 256:
        raise ValueError("fixed prefix must contain 1--256 self-consistent lines")
    addresses = []
    sets = collections.Counter()
    for rank, line in enumerate(lines):
        address = int(line["paddr"])
        if int(line["rank"]) != rank:
            raise ValueError("fixed prefix ranks are not consecutive")
        if address & 63:
            raise ValueError(f"prefix address 0x{address:x} is not line aligned")
        if address >= (1 << 56):
            raise ValueError(f"prefix address 0x{address:x} exceeds CSR payload")
        cache_set = (address // 64) % 64
        if int(line["cache_set"]) != cache_set:
            raise ValueError(f"prefix address 0x{address:x} has inconsistent set")
        addresses.append(address)
        sets[cache_set] += 1
    if len(set(addresses)) != len(addresses):
        raise ValueError("fixed prefix contains duplicate addresses")
    if max(sets.values()) > 8:
        raise ValueError("fixed prefix exceeds the eight-way I-cache in one set")

    body = "\n".join(f"    0x{address:016x}UL," for address in addresses)
    return f"""/* Generated by linux-tests/emit_icache_prefix_header.py.
 * Source policy: {table['policy']}
 */
#ifndef BP_ICACHE_PREFIX_H
#define BP_ICACHE_PREFIX_H

#define BP_ICACHE_PREFIX_COUNT {len(addresses)}U
static const unsigned long bp_icache_prefix[BP_ICACHE_PREFIX_COUNT] = {{
{body}
}};

#endif
"""


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--results",
        type=Path,
        default=root / "logs/cache-resume-trace-model-20261030/results.json",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parent
        / "opensbi-platform/blackparrot/icache_prefix.h",
    )
    args = parser.parse_args()
    text = render(json.loads(args.results.read_text()))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    print(f"wrote {args.output} with {text.count('UL,')} cache lines")


if __name__ == "__main__":
    main()
