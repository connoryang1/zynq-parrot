#!/usr/bin/env python3
"""Generate deterministic warm and measured binary-index paths."""

from pathlib import Path


MEASURED_ENTRIES = 2047  # 2^11 - 1: every absent-key search takes 11 levels.
WARM_ENTRIES = 31        # 2^5 - 1: compact instruction-path warmup data.
WORKERS = 10


def queries(entries):
    # Odd keys are absent from an index containing even keys. Spread them
    # across the full logical range while keeping every result in range.
    return [2 * (((i + 1) * entries) // (WORKERS + 1)) + 1 for i in range(WORKERS)]


def search_path(entries, key):
    lower, length = 0, entries
    path = []
    while length:
        half = length >> 1
        middle = lower + half
        path.append(middle)
        if middle * 2 < key:
            lower = middle + 1
            length -= half + 1
        else:
            length = half
    return path


def emit_indexes(name, entries):
    all_queries = queries(entries)
    paths = [search_path(entries, key) for key in all_queries]
    levels = len(paths[0])
    assert all(len(path) == levels for path in paths)
    lines = [
        f"static const volatile struct index_line {name}[NANO_LOOKUP_WORKERS][{levels}]",
        "  __attribute__((aligned(4096), used)) = {",
    ]
    for key, path in zip(all_queries, paths):
        lines.append("  {")
        for step, middle in enumerate(path):
            next_step = step + 1 if step + 1 < levels else 0
            next_less = next_step if middle * 2 < key else 0
            next_ge = next_step if middle * 2 >= key else 0
            lines.append(
                f"    {{ UINT64_C({middle * 2}), {next_less}, {next_ge}, {{0}} }},"
            )
        lines.append("  },")
    lines.append("};")
    return lines, levels


def emit_queries(name, entries):
    values = ", ".join(f"UINT64_C({value})" for value in queries(entries))
    return [f"static const uint64_t {name}[NANO_LOOKUP_WORKERS] = {{ {values} }};"]


measured_lines, measured_levels = emit_indexes("nano_measured_indexes", MEASURED_ENTRIES)
warm_lines, warm_levels = emit_indexes("nano_warm_indexes", WARM_ENTRIES)
lines = [
    "/* Generated by generate_nano_lookup_data.py; do not edit.",
    " * Each immutable cache-line node carries a key and branch-selected next link.",
    " */",
    "#ifndef NANO_LOOKUP_DATA_H",
    "#define NANO_LOOKUP_DATA_H",
    "",
    f"#define NANO_LOOKUP_MEASURED_ENTRIES {MEASURED_ENTRIES}",
    f"#define NANO_LOOKUP_WARM_ENTRIES {WARM_ENTRIES}",
    f"#define NANO_LOOKUP_MEASURED_LEVELS {measured_levels}",
    f"#define NANO_LOOKUP_WARM_LEVELS {warm_levels}",
    f"#define NANO_LOOKUP_WORKERS {WORKERS}",
    "",
]
lines.extend(measured_lines)
lines.append("")
lines.extend(warm_lines)
lines.append("")
lines.extend(emit_queries("nano_measured_queries", MEASURED_ENTRIES))
lines.extend(emit_queries("nano_warm_queries", WARM_ENTRIES))
lines.extend(["", "#endif", ""])

Path(__file__).with_name("nano_lookup_data.h").write_text("\n".join(lines))
